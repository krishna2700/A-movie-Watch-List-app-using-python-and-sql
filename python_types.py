# Python Types Explanation
# Python is dynamically typed, meaning variables can hold any type (int, str, float, bool, list, dict, etc.) without explicit declaration.
# Types are determined at runtime, and you can use type hints (e.g., def func(x: int) -> str:) for better code clarity and tooling support.
# Built-in functions like type() and isinstance() help check types, while Python 3.5+ supports static type checking via tools like mypy.
