# React Types Explained in 3 Lines
# 1. React uses TypeScript types like FC (FunctionComponent), ReactNode, and ReactElement to define component signatures and their return values.
# 2. Props are typed via interfaces or type aliases (e.g., `type Props = { name: str }`) ensuring components receive the correct data shapes at compile time.
# 3. Hooks like useState and useRef are generic (`useState<number>(0)`) allowing type-safe state and ref management throughout the component lifecycle.
